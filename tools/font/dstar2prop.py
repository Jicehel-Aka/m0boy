#!/usr/bin/env python3
"""The option menus' font: the dstar mono font (greenfont, by r043v) rendered
proportional — each glyph cropped to its ink, left bearing kept, same 2 bits
a pixel.  Reads the original tables from git HEAD and rewrites
targets/meta/platform/src/meta_font.h.  Run from the repository root."""
import pathlib, re, subprocess

root = pathlib.Path(__file__).resolve().parents[2]
src = subprocess.run(["git", "show", "HEAD:targets/meta/platform/src/meta_font.h"],
                     capture_output=True, text=True, cwd=root, check=True).stdout
pairs = re.findall(r"\{([0-9A-Fa-fx, ]+)\}, /\* (.*?) \*/", src)
pairs = [(v, c.strip() or " ") for v, c in pairs if "0x" in v]
assert len(pairs) == 91, len(pairs)

glyphs = []
for vals, chname in pairs:
    ch = chname if len(chname) == 1 else " "
    words = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{4})", vals)]
    px = [[(words[r] >> (14 - 2 * c)) & 3 for c in range(8)] for r in range(8)]
    cols = [c for c in range(8) if any(px[r][c] for r in range(8))]
    if not cols:
        glyphs.append((ch, 4, 0, [], 0))          # blank: 4 pixels of advance
        continue
    left, right = cols[0], cols[-1]
    w = right - left + 1
    stride = (w + 3) // 4
    rows = []
    for r in range(8):
        bs = [0] * stride
        for c in range(left, right + 1):
            v = px[r][c]
            if v:
                j = c - left
                bs[j >> 2] |= v << (6 - 2 * (j & 3))
        rows.append(bs)
    glyphs.append((ch, left + w + 1, left, rows, w))

out = ["/* The dstar font (greenfont, by r043v) as 2 bits a pixel (0 transparent),\n"
       " * rendered proportional: each glyph is cropped to its ink, its left bearing\n"
       " * kept (the comma stays under its letter), from the one-16-bit-word-per-row\n"
       " * mono font at origin.  Generated by tools/font/dstar2prop.py.  Do not edit.\n"
       " * glyph of character c: meta_font_map[c - META_FONT_FIRST]. */"]
out.append("#ifndef META_FONT_H\n#define META_FONT_H\n")
out.append("#include <stdint.h>\n")
out.append("#define META_FONT_FIRST 0x20")
out.append(f"#define META_FONT_COUNT {len(glyphs)}")
out.append("#define META_FONT_HEIGHT 8\n")
out.append("static const uint32_t meta_font_colours[3] = {0x21714E, 0x75F9D8, 0x000000};")
out.append("/* glyph index of character c, 0xff: none (drawn blank) */")
out.append("static const uint8_t meta_font_map[96] = {")
table = []
for i in range(96):
    ch = chr(0x20 + i)
    hit = next((n for n, (c, *_) in enumerate(glyphs) if c == ch), None)
    table.append("0xff" if hit is None else str(hit))
out.append("    " + ",".join(table) + "\n};")
out.append("/* advance, left bearing and ink width, in pixels */")
out.append(f"static const uint8_t meta_font_advance[{len(glyphs)}] = {{"
           + ",".join(str(g[1]) for g in glyphs) + "};")
out.append(f"static const uint8_t meta_font_left[{len(glyphs)}] = {{"
           + ",".join(str(g[2]) for g in glyphs) + "};")
out.append(f"static const uint8_t meta_font_w[{len(glyphs)}] = {{"
           + ",".join(str(g[4]) for g in glyphs) + "};")
out.append("/* ink rows, 2 bits a pixel MSB-first, (w+3)/4 bytes a row */")
offsets, blob = [], []
for ch, adv, left, rows, w in glyphs:
    offsets.append(len(blob))
    for r in rows:
        blob += r
out.append(f"static const uint16_t meta_font_off[{len(glyphs)}] = {{"
           + ",".join(str(o) for o in offsets) + "};")
out.append("static const uint8_t meta_font_rows[] = {")
for i in range(0, len(blob), 12):
    out.append("    " + ",".join("0x%02x" % b for b in blob[i:i + 12]) + ",")
out.append("};\n#endif")
path = root / "targets/meta/platform/src/meta_font.h"
path.write_text("\n".join(out) + "\n")
print("meta_font.h: %d glyphs, %d B of bitmap" % (len(glyphs), len(blob)))
