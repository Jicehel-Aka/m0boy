#!/usr/bin/env python3
"""A TrueType font as the option menus' bitmap font: variable width, 2 bits a
pixel (0 transparent, 1..3 = the three menu colours, antialiasing over the
three), rows packed MSB-first at exact width, one glyph per printable ASCII
character (the menus and the game titles never draw anything else).

Result in targets/common/platform/m0_font.h, compiled into every
firmware: regenerate upstream with the TTF at hand (the binary keeps the
rasterised glyphs, a few hundred bytes a font), never at build time.

Usage: ttf2menu.py FONT.ttf [SIZE]
"""
import pathlib
import sys
from PIL import Image, ImageDraw, ImageFont

out_path = pathlib.Path(__file__).resolve().parents[2] / "targets/common/platform/m0_font.h"
ttf = sys.argv[1] if len(sys.argv) > 1 else "/home/m/dev/fantasti/font.ttf"
size = int(sys.argv[2]) if len(sys.argv) > 2 else 11
first, last = 0x20, 0x7e
chars = [chr(c) for c in range(first, last + 1)]
height = 8          # rows per glyph, descenders clipped (an 8-row font, as before)
levels = 3          # opaque colours; antialiasing quantised onto them
SCALE = 4           # the glyph is rendered 4x bigger, then box-downscaled

fbig = ImageFont.truetype(ttf, size * SCALE)  # supersampled, box-downscaled
abig = fbig.getmetrics()[0]
font = ImageFont.truetype(ttf, size)
# the row the baseline sits on: caps on the last row, descenders clipped
baseline = height - 1

stroke = SCALE // 2                        # the boldness, part of the box
glyphs = {}
for ch in chars:
    b = fbig.getbbox(ch)
    left = max(0, b[0] - stroke)            # the stroke grows past the bbox
    w = max(1, min(12, (b[2] + stroke - left + SCALE - 1) // SCALE))
    img = Image.new("L", (w * SCALE, (height + 2) * SCALE), 0)
    ImageDraw.Draw(img).text((-left, (baseline + 1) * SCALE - abig), ch, font=fbig,
                             fill=255, stroke_width=stroke, stroke_fill=255)
    small = img.resize((w, height), Image.BOX)
    px = small.load()
    rows = []
    for r in range(height):
        line = []
        for x in range(w):
            c = px[x, r]                        # coverage 0..255
            # crisp at 8 rows: solid strokes, one colour (a second level
            # reads as noise this small)
            line.append(0 if c < 70 else 2)
        rows.append(line)
    # the TTF's textured edges speckle at 8 rows: drop isolated pixels, fill
    # single-pixel holes (one pass each, orthogonal neighbours)
    for _ in range(1):
        for r in range(height):
            for x in range(w):
                n = sum(rows[y][x] > 0 for y, x in ((r-1,x),(r+1,x),(r,x-1),(r,x+1))
                        if 0 <= y < height and 0 <= x < w)
                if rows[r][x] and n == 0: rows[r][x] = 0
    glyphs[ch] = (w, rows)

# advance widths: the bitmap width + 1 spacing pixel, space at least 4
adv = {ch: min(12, max(4, glyphs[ch][0] + 1)) for ch in chars}

out = []
out.append("""/* Generated by tools/font/ttf2menu.py from %s at size %d: the option
 * menus' font, variable width, 2 bits a pixel (0 transparent, 1..3 the menu
 * colours), rows packed MSB-first at exact width, 8 rows (descenders
 * clipped).  Only the printable ASCII the menus and game titles draw.
 * Do not edit: regenerate upstream, the binary keeps the rasterised glyphs.
 * glyph of character c: m0_font_map[c - M0_FONT_FIRST], 0xff: none. */""" % (ttf, size))
out.append("#ifndef M0_FONT_H\n#define M0_FONT_H\n")
out.append("#include <stdint.h>\n")
out.append(f"#define M0_FONT_FIRST 0x{first:02x}")
out.append("#define M0_FONT_COUNT %d" % len(chars))
out.append("#define M0_FONT_HEIGHT %d" % height)
out.append("#define M0_FONT_MAXWIDTH %d" % max(adv.values()))
out.append("")
out.append("static const uint32_t m0_font_colours[3] = {0x21714E, 0x75F9D8, 0x000000};")
out.append("static const uint8_t m0_font_map[96] = {")
out.append("    " + ",".join(str(i) for i in range(len(chars))) + "\n};")
out.append("static const uint8_t m0_font_advance[%d] = {" % len(chars))
line = "   "
for ch in chars:
    line += " %d," % adv[ch]
    if len(line) > 100:
        out.append(line); line = "   "
out.append(line + "\n};")
out.append("/* rows of each glyph, (width+3)/4 bytes a row, 2 bits a pixel MSB-first */")
out.append("static const uint8_t m0_font_rows[] = {")
offsets, blob = [], []
for ch in chars:
    w, rows = glyphs[ch]
    stride = (w + 3) // 4
    offsets.append((len(blob), w, stride))
    out.append("  /* '%s' w=%d */" % (ch if ch not in "'\\" else {"'": "\\'", "\\": "\\\\"}[ch], w))
    for r in rows:
        bs = [0] * stride
        for x, v in enumerate(r):
            if v:
                bs[x >> 2] |= v << (6 - 2 * (x & 3))
        line = "   " + " ".join("0x%02x," % b for b in bs)
        out.append(line)
        blob += bs
out.append("};")
out.append("""
/* row r of glyph c begins at m0_font_rows + m0_font_off[c] + r * m0_font_stride[c] */
#define M0_FONT_STRIDE(c) (((m0_font_advance[(c)] - 1) >> 2) + 1)
static const uint16_t m0_font_off[%d] = {""" % len(chars))
line = "   "
for i, (off, w, stride) in enumerate(offsets):
    line += " %d," % off
    if len(line) > 100:
        out.append(line); line = "   "
out.append(line + "\n};")
out.append("""
#endif
""")
pathlib.Path(out_path).write_text("\n".join(out))
total = len(blob) + len(chars) * 2 + len(chars) + 96
print("%d glyphs, bitmap %d B, tables ~%d B -> about %d B (was 1638 mono 8x8)"
      % (len(chars), len(blob), len(chars) * 3, total))
