#!/usr/bin/env python3
"""Convert a Gm4kr-exported agf font (Gdl's 4-bit RLE format, one
`unsigned char <name><n>[]` array per glyph, from ' ' up) into meta_font.h
for the META option menu: 2 bits a pixel (0 transparent, 1..3 the font's
colours), one 16-bit word a row, leftmost pixel in bits 15:14.  The font
may use three colours at most, shared by every glyph.

    agf2meta.py greenfont.h ["credit line"] > targets/meta/platform/src/meta_font.h
"""
import re
import sys


def decode(d):
    if d[:3] != b"agf":
        raise ValueError("not agf")
    n = d[3]
    sx, sy = d[8] | d[9] << 8, d[10] | d[11] << 8
    p = 16
    pal = []
    for _ in range(n):
        pal.append(int.from_bytes(d[p:p + 4], "little") & 0xFFFFFF)
        p += 4
    img = [[0] * sx for _ in range(sy)]
    for y in range(sy):
        runs = d[p]
        p += 1
        x = 0
        for _ in range(runs):
            jump, size = d[p], d[p + 1]
            p += 2
            x += jump
            px = []
            for _ in range((size + 1) // 2):
                px += [d[p] >> 4, d[p] & 15]
                p += 1
            for i in range(size):
                img[y][x + i] = px[i] + 1
            x += size
    return sx, sy, pal, img


src = open(sys.argv[1], encoding="latin-1").read()
glyphs = []
for m in re.finditer(r"unsigned char (\w+?)(\d+)\[\d+\]\s*=\s*\{([^}]*)\}", src):
    data = bytes(int(x, 0) for x in m.group(3).replace("\n", " ").split(",") if x.strip())
    glyphs.append((int(m.group(2)), decode(data)))
glyphs.sort(key=lambda g: g[0])
if [n for n, _ in glyphs] != list(range(len(glyphs))):
    sys.exit("glyph numbers are not 0..%d" % (len(glyphs) - 1))

palette = []
for _, (sx, sy, pal, img) in glyphs:
    if pal and palette and pal != palette:
        sys.exit("glyphs use different palettes")
    if pal:
        palette = pal
if len(palette) > 3:
    sys.exit("more than three colours")
heights = {sy for _, (sx, sy, _, _) in glyphs}
if len(heights) != 1 or max(sx for _, (sx, *_r) in glyphs) > 8:
    sys.exit("glyphs must share a height and be at most 8 pixels wide")
height = heights.pop()

credit = sys.argv[2] if len(sys.argv) > 2 else ""
out = ["/* Generated by targets/meta/tools/font/agf2meta.py from %s:" % sys.argv[1].split("/")[-1],
       " * a Gdl agf font as 2 bits a pixel (0 transparent), a 16-bit word a row,",
       " * leftmost pixel in bits 15:14, character META_FONT_FIRST + n.  Do not edit."]
if credit:
    out.append(" * " + credit)
out[-1] += " */"
out += ["#ifndef META_FONT_H", "#define META_FONT_H", "", "#include <stdint.h>", "",
        "#define META_FONT_FIRST ' '", "#define META_FONT_COUNT %d" % len(glyphs),
        "#define META_FONT_HEIGHT %d" % height, "",
        "static const uint32_t meta_font_colours[3] = {%s};" %
        ", ".join("0x%06X" % c for c in (palette + [0, 0, 0])[:3]),
        "static const uint8_t meta_font_width[META_FONT_COUNT] = {"]
widths = [sx for _, (sx, *_r) in glyphs]
for i in range(0, len(widths), 16):
    out.append("    " + " ".join("%d," % w for w in widths[i:i + 16]))
out.append("};")
out.append("static const uint16_t meta_font_rows[META_FONT_COUNT][META_FONT_HEIGHT] = {")
for n, (sx, sy, pal, img) in glyphs:
    words = []
    for row in img:
        w = 0
        for x, v in enumerate(row):
            w |= (v & 3) << (14 - 2 * x)
        words.append("0x%04X" % w)
    ch = chr(32 + n)
    out.append("    {%s}, /* %s */" % (", ".join(words), ch if ch not in "\\*/" else "'" + ch + "'"))
out += ["};", "", "#endif", ""]
sys.stdout.write("\n".join(out))
