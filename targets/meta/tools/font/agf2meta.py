#!/usr/bin/env python3
"""Copy a Gm4kr-exported agf font (one `unsigned char <name><n>[]` array per
glyph, from ' ' up) into meta_font.h for the META option menu.

The glyphs stay in Gdl's 4-bit agf format, byte for byte; meta_menu.cpp
draws them with a small RLE blitter.

    agf2meta.py greenfont.h ["credit line"] > targets/meta/platform/src/meta_font.h
"""
import re
import sys

src = open(sys.argv[1], encoding="latin-1").read()
glyphs = []
for m in re.finditer(r"unsigned char (\w+?)(\d+)\[\d+\]\s*=\s*\{([^}]*)\}", src):
    data = [int(x, 0) for x in m.group(3).replace("\n", " ").split(",") if x.strip()]
    if data[:3] != [0x61, 0x67, 0x66]:
        sys.exit("glyph %s%s is not agf" % (m.group(1), m.group(2)))
    glyphs.append((int(m.group(2)), data))
glyphs.sort()
if [n for n, _ in glyphs] != list(range(len(glyphs))):
    sys.exit("glyph numbers are not 0..%d" % (len(glyphs) - 1))

credit = sys.argv[2] if len(sys.argv) > 2 else ""
out = ["/* Generated by targets/meta/tools/font/agf2meta.py from %s:" % sys.argv[1].split("/")[-1],
       " * Gdl agf (4-bit RLE) glyphs, character ' ' + n.  Do not edit."]
if credit:
    out.append(" * " + credit)
out[-1] += " */"
out += [
       "#ifndef META_FONT_H", "#define META_FONT_H", "", "#include <stdint.h>", "",
       "#define META_FONT_FIRST ' '", "#define META_FONT_COUNT %d" % len(glyphs), ""]
for n, data in glyphs:
    rows = [", ".join("0x%02X" % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    out.append("static const uint8_t meta_font_%d[%d] = {\n    %s};" % (n, len(data), ",\n    ".join(rows)))
out.append("")
out.append("static const uint8_t *const meta_font[META_FONT_COUNT] = {")
for i in range(0, len(glyphs), 8):
    out.append("    " + " ".join("meta_font_%d," % n for n, _ in glyphs[i:i + 8]))
out += ["};", "", "#endif", ""]
sys.stdout.write("\n".join(out))
